#include "libft.h"

char	*ft_strdup(const char *s1)
{
	size_t	slen;
	char	*cpy;
	int		i;

	slen = ft_strlen(s1);
	i = 0;
	if (!s1)
		return (NULL);
	cpy = malloc(slen + 1 * sizeof(char));
	if (!cpy)
		return (NULL);
	while (s1[i])
	{
		cpy[i] = s1[i];
		i++;
	}
	cpy[i] = 0;
	return (cpy);
}
